import { chromium } from "@playwright/test";
const browser = await chromium.launch({ channel: "msedge" });
const ctx = await browser.newContext({ viewport: { width: 1448, height: 1086 } });
const s = JSON.stringify({ actor: { kind: "staff", userId: process.env.AS ?? "u-lan" }, startedAt: "2026-10-05T08:00:00+07:00", via: "demo" });
await ctx.addInitScript((v) => { sessionStorage.setItem("edumanage-demo-session", v); localStorage.setItem("edumanage-demo-session-last", v); }, s);
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e).slice(0, 200)));
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errors.push(m.text().slice(0, 200)); });
await page.goto("http://localhost:3000" + (process.argv[2] ?? "/preview/states"), { waitUntil: "networkidle" });
await page.waitForTimeout(3000);
const t0 = Date.now();
if (process.argv[3]) await page.getByText(process.argv[3]).first().click({ timeout: 8000 }).catch((e) => errors.push("click: " + String(e).slice(0, 80)));
else await page.evaluate(() => { localStorage.setItem("edumanage-demo-scenario", JSON.stringify({ write: "fail-next", read: "normal", latencyMs: 180 })); window.dispatchEvent(new StorageEvent("storage")); });
await page.waitForTimeout(1500);
const alive = await Promise.race([page.evaluate(() => document.title).then(() => "alive"), new Promise((r) => setTimeout(() => r("frozen"), 5000))]);
if (process.argv[4] && alive === "alive") await page.screenshot({ path: process.argv[4] });
console.log(alive, Date.now() - t0, JSON.stringify(errors.slice(0, 6)));
await page.evaluate(() => localStorage.removeItem("edumanage-demo-scenario")).catch(() => {});
await browser.close();
